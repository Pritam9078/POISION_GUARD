/**
 * PoisonGuard deterministic detection rules — methodology v1.0.
 *
 * Every rule is a pure function of normalized chain data. No network, no AI, no randomness.
 * Each finding separates on-chain FACTS (tx hashes, values) from DERIVED measurements
 * (similarity lengths) and the INTERPRETATION (why it may matter).
 */
import { canonicalToken, canonicalBySymbol, KNOWN_SPENDERS } from '../../shared/chains.js'

export const METHODOLOGY_VERSION = '1.0'
export const UNLIMITED_THRESHOLD = 2n ** 128n // ≥ this is treated as "effectively unlimited"

export const RULES = {
  'PG-POISON-001': {
    name: 'Lookalike counterparty', category: 'Address poisoning', defaultSeverity: 'high',
    description: 'An address that shares a leading and trailing hex sequence with an established counterparty (one this wallet has actually paid, or a workspace trusted recipient) appeared in the wallet history without the wallet ever initiating a value transfer to it.',
    thresholds: { minPrefix: 4, minSuffix: 4, weakPrefix: 3, weakSuffix: 3, weakTotal: 7 },
    knownFalsePositives: 'Vanity addresses generated by the same owner; exchange deposit addresses that share prefixes by chance (rare above 8 matching characters).',
  },
  'PG-POISON-002': {
    name: 'Zero-value transfer spoofing', category: 'Address poisoning', defaultSeverity: 'medium',
    description: 'A zero-value ERC-20 Transfer log names this wallet as the sender although the wallet did not send the transaction. Many tokens allow transferFrom(victim, x, 0) without an allowance, which plants a fake outgoing entry in explorer history.',
    thresholds: {},
    knownFalsePositives: 'Contract wallets that legitimately batch zero-value calls; some airdrop claim contracts.',
  },
  'PG-POISON-003': {
    name: 'Unsolicited dust burst', category: 'Dust pattern', defaultSeverity: 'medium',
    description: 'Several distinct senders transferred zero or dust amounts to this wallet within a short window. Dust bursts commonly precede or accompany poisoning campaigns.',
    thresholds: { minSenders: 3, windowHours: 72 },
    knownFalsePositives: 'Legitimate airdrop campaigns and promotional token distributions.',
  },
  'PG-POISON-004': {
    name: 'Counterfeit token transfer', category: 'Address poisoning', defaultSeverity: 'medium',
    description: 'A token claiming a well-known symbol (e.g. USDC, USDT) but deployed at a non-canonical contract address transferred to or from this wallet. Fake-symbol tokens are used to make poisoned history entries look like real stablecoin payments.',
    thresholds: {},
    knownFalsePositives: 'Bridged/legacy versions of a token that are not in the canonical registry (e.g. USDC.e).',
  },
  'PG-APPROVAL-001': {
    name: 'Unlimited token allowance', category: 'Token approval', defaultSeverity: 'high',
    description: 'The current on-chain allowance is effectively unlimited (≥ 2^128 base units). The spender can move the full token balance at any time without a further signature.',
    thresholds: { unlimitedAtOrAbove: '2^128' },
    knownFalsePositives: 'Unlimited approvals to well-known routers are common and usually intentional; they are reported at low severity as exposure, not as malicious.',
  },
  'PG-APPROVAL-002': {
    name: 'Allowance to externally-owned account', category: 'Token approval', defaultSeverity: 'high',
    description: 'A non-zero allowance is granted to an address with no contract code. Legitimate protocols almost never require approving a plain wallet; this is a common drainer pattern.',
    thresholds: {},
    knownFalsePositives: 'Deliberate approvals to a personal hot wallet or a smart-account address that is not yet deployed (counterfactual).',
  },
}

const SEV_WEIGHT = { critical: 90, high: 70, medium: 45, low: 20, info: 5 }

const hex = (a) => a.toLowerCase().slice(2)
export function prefixLen(a, b) { const x = hex(a), y = hex(b); let i = 0; while (i < 40 && x[i] === y[i]) i++; return i }
export function suffixLen(a, b) { const x = hex(a), y = hex(b); let i = 0; while (i < 40 && x[39 - i] === y[39 - i]) i++; return i }

/** Returns { prefix, suffix, strength: 'strong'|'weak'|null } for two distinct addresses. */
export function similarity(a, b, t = RULES['PG-POISON-001'].thresholds) {
  if (!a || !b || a.toLowerCase() === b.toLowerCase()) return { prefix: 40, suffix: 40, strength: null }
  const prefix = prefixLen(a, b), suffix = suffixLen(a, b)
  let strength = null
  if (prefix >= t.minPrefix && suffix >= t.minSuffix) strength = 'strong'
  else if (prefix >= t.weakPrefix && suffix >= t.weakSuffix && prefix + suffix >= t.weakTotal) strength = 'weak'
  return { prefix, suffix, strength }
}

function isDust(value, decimals) {
  const v = BigInt(value)
  if (v === 0n) return true
  if (decimals == null || decimals < 2) return false
  return v < 10n ** BigInt(decimals - 2) // < 0.01 whole tokens
}

const short = (a) => `${a.slice(0, 8)}…${a.slice(-6)}`

/**
 * Run all rules.
 * @param {object} input
 *  subject (lowercase address), chainId, transfers[], tokenMeta {addr: {symbol, decimals}},
 *  approvals[{ token, spender, allowance (string), spenderIsContract, lastBlock }], trusted[{ address, label }],
 *  focusAddresses? (Set) — restrict findings to these related addresses (transaction scans)
 */
export function runRules(input) {
  const { subject, transfers = [], tokenMeta = {}, approvals = [], trusted = [], focusAddresses = null } = input
  const s = subject.toLowerCase()
  const findings = []
  const keep = (addr) => !focusAddresses || focusAddresses.has(addr)

  // Established counterparties: addresses this wallet initiated a non-zero transfer to, plus trusted recipients.
  const established = new Map()
  for (const t of transfers) {
    const initiatedBySubject = t.kind === 'native' ? t.from === s : (t.from === s && (t.txFrom == null || t.txFrom === s))
    if (initiatedBySubject && t.to && t.to !== s && BigInt(t.value) > 0n && !isDust(t.value, tokenMeta[t.token]?.decimals ?? 18)) {
      if (!established.has(t.to)) established.set(t.to, { source: 'Outgoing transfer history', tx: t })
    }
  }
  for (const r of trusted) if (!established.has(r.address)) established.set(r.address, { source: `Trusted recipient "${r.label}"`, trusted: true })

  // Counterparties the wallet never paid — candidates for planted lookalikes.
  const byCounterparty = new Map()
  for (const t of transfers) {
    const other = t.from === s ? t.to : t.from
    if (!other || other === s || established.has(other)) continue
    if (!byCounterparty.has(other)) byCounterparty.set(other, [])
    byCounterparty.get(other).push(t)
  }

  // ── PG-POISON-001 ──
  for (const [cand, txs] of byCounterparty) {
    if (!keep(cand)) continue
    let best = null
    for (const [est, info] of established) {
      const sim = similarity(cand, est)
      if (!sim.strength) continue
      if (!best || sim.prefix + sim.suffix > best.sim.prefix + best.sim.suffix) best = { est, info, sim }
    }
    if (!best) continue
    const zeroOrDust = txs.filter((t) => isDust(t.value, tokenMeta[t.token]?.decimals ?? 18))
    const total = best.sim.prefix + best.sim.suffix
    const strong = best.sim.strength === 'strong'
    const confidence = Math.min(95, (strong ? 62 : 45) + (total - 8) * 4 + (zeroOrDust.length ? 10 : 0) + (best.info.trusted ? 5 : 0))
    const severity = strong && zeroOrDust.length ? 'high' : strong ? 'medium' : 'low'
    findings.push({
      ruleId: 'PG-POISON-001', category: RULES['PG-POISON-001'].category, severity, confidence,
      title: 'Lookalike address in transfer history',
      summary: `${short(cand)} matches the first ${best.sim.prefix} and last ${best.sim.suffix} hex characters of ${short(best.est)} (${best.info.source}), but this wallet never initiated a value transfer to it. ${zeroOrDust.length ? `${zeroOrDust.length} zero/dust transfer(s) involved it — a typical poisoning setup.` : ''}`.trim(),
      subjectAddress: s, relatedAddress: cand,
      evidence: [
        { kind: 'derived', label: 'Lookalike address', source: 'Transfer history', value: cand },
        { kind: best.info.trusted ? 'derived' : 'onchain_fact', label: 'Established counterparty', source: best.info.source, value: best.est, txHash: best.info.tx?.txHash, blockNumber: best.info.tx?.blockNumber },
        { kind: 'derived', label: 'Similarity', source: 'PG-POISON-001', value: `prefix ${best.sim.prefix} · suffix ${best.sim.suffix} hex chars (${best.sim.strength})` },
        ...txs.slice(0, 5).map((t) => ({ kind: 'onchain_fact', label: t.kind === 'native' ? 'Native transfer' : 'ERC-20 Transfer log', source: 'Chain data', value: `${t.from === s ? 'out' : 'in'} · value ${t.value} · token ${t.token ?? 'native'}`, txHash: t.txHash, blockNumber: t.blockNumber, logIndex: t.logIndex, observedAt: t.timestamp })),
        { kind: 'interpretation', label: 'Interpretation', source: 'Rule rationale', value: 'Lookalike addresses are planted so that a user copying a recipient from history pastes the attacker address. Similarity alone does not prove malicious intent.' },
      ],
      limitations: RULES['PG-POISON-001'].knownFalsePositives + ' Only the transfer history available to this scan was compared.',
      recommendation: 'Never copy recipients from transaction history. Use a verified address book / trusted recipient list and compare the full address, not just the first and last characters.',
    })
  }

  // ── PG-POISON-002 ──
  const spoofs = transfers.filter((t) => t.kind === 'erc20' && t.from === s && BigInt(t.value) === 0n && t.txFrom && t.txFrom !== s && keep(t.to))
  const unknownSender = transfers.filter((t) => t.kind === 'erc20' && t.from === s && BigInt(t.value) === 0n && !t.txFrom && keep(t.to))
  if (spoofs.length || unknownSender.length) {
    const confirmed = spoofs.length > 0
    findings.push({
      ruleId: 'PG-POISON-002', category: RULES['PG-POISON-002'].category, severity: 'medium', confidence: confirmed ? 85 : 55,
      title: 'Zero-value transfers spoofed in your name',
      summary: confirmed
        ? `${spoofs.length} zero-value Transfer log(s) list this wallet as sender, but the transactions were sent by a different address. Your wallet did not authorize these.`
        : `${unknownSender.length} zero-value Transfer log(s) list this wallet as sender; the originating transaction sender could not be confirmed.`,
      subjectAddress: s, relatedAddress: (spoofs[0] || unknownSender[0]).to,
      evidence: [...spoofs, ...unknownSender].slice(0, 8).map((t) => ({ kind: 'onchain_fact', label: 'Zero-value Transfer', source: 'ERC-20 Transfer event', value: `to ${t.to} · token ${t.token}${t.txFrom ? ` · tx sent by ${t.txFrom}` : ''}`, txHash: t.txHash, blockNumber: t.blockNumber, logIndex: t.logIndex, observedAt: t.timestamp })),
      limitations: RULES['PG-POISON-002'].knownFalsePositives,
      recommendation: 'No funds moved in these entries. Hide zero-value transfers in your wallet/explorer and never reuse their recipient addresses.',
    })
  }

  // ── PG-POISON-003 ──
  const inboundDust = transfers.filter((t) => t.to === s && t.from !== s && isDust(t.value, tokenMeta[t.token]?.decimals ?? 18))
  if (inboundDust.length) {
    const cfg = RULES['PG-POISON-003'].thresholds
    const withTime = inboundDust.filter((t) => t.timestamp || t.blockNumber != null).sort((a, b) => Number(BigInt(a.blockNumber) - BigInt(b.blockNumber)))
    const senders = new Set(withTime.map((t) => t.from))
    const windowOk = (() => {
      const ts = withTime.filter((t) => t.timestamp).map((t) => new Date(t.timestamp).getTime())
      if (ts.length < 2) return true // no timestamps: count senders only (documented limitation)
      return Math.max(...ts) - Math.min(...ts) <= cfg.windowHours * 3600_000 * 10 // look across up to 10 windows
    })()
    if (senders.size >= cfg.minSenders && windowOk && (!focusAddresses || [...senders].some(keep))) {
      findings.push({
        ruleId: 'PG-POISON-003', category: RULES['PG-POISON-003'].category, severity: 'medium', confidence: Math.min(80, 50 + senders.size * 5),
        title: 'Repeated zero-value or dust transfers from unrelated senders',
        summary: `${inboundDust.length} zero/dust transfer(s) from ${senders.size} distinct senders were received. Dust bursts often accompany address-poisoning campaigns.`,
        subjectAddress: s, relatedAddress: [...senders][0],
        evidence: [
          { kind: 'derived', label: 'Distinct senders', source: 'Transfer history', value: String(senders.size) },
          ...withTime.slice(0, 6).map((t) => ({ kind: 'onchain_fact', label: 'Inbound dust', source: 'Chain data', value: `from ${t.from} · value ${t.value} · token ${t.token ?? 'native'}`, txHash: t.txHash, blockNumber: t.blockNumber, observedAt: t.timestamp })),
        ],
        limitations: RULES['PG-POISON-003'].knownFalsePositives,
        recommendation: 'Treat unsolicited tokens as untrusted. Do not interact with them or visit URLs embedded in token names.',
      })
    }
  }

  // ── PG-POISON-004 ──
  const fakeSeen = new Map()
  for (const t of transfers) {
    if (t.kind !== 'erc20' || canonicalToken(input.chainId, t.token)) continue
    const sym = tokenMeta[t.token]?.symbol
    if (!sym || !canonicalBySymbol(input.chainId, sym.trim()).length) continue
    if (!keep(t.from === s ? t.to : t.from)) continue
    if (!fakeSeen.has(t.token)) fakeSeen.set(t.token, [])
    fakeSeen.get(t.token).push(t)
  }
  for (const [token, txs] of fakeSeen) {
    const sym = tokenMeta[token].symbol
    const canon = canonicalBySymbol(input.chainId, sym)[0]
    findings.push({
      ruleId: 'PG-POISON-004', category: RULES['PG-POISON-004'].category, severity: 'medium', confidence: 75,
      title: `Counterfeit "${sym}" token in history`,
      summary: `Token ${short(token)} uses the symbol ${sym} but is not the canonical ${sym} contract (${short(canon.address)}). ${txs.length} transfer(s) involve it.`,
      subjectAddress: s, relatedAddress: txs[0].from === s ? txs[0].to : txs[0].from,
      evidence: [
        { kind: 'onchain_fact', label: 'Token contract', source: 'Transfer log emitter', value: token },
        { kind: 'derived', label: 'Canonical contract', source: 'PoisonGuard token registry', value: canon.address },
        ...txs.slice(0, 4).map((t) => ({ kind: 'onchain_fact', label: 'Transfer', source: 'ERC-20 Transfer event', value: `${t.from} → ${t.to} · ${t.value}`, txHash: t.txHash, blockNumber: t.blockNumber })),
      ],
      limitations: RULES['PG-POISON-004'].knownFalsePositives,
      recommendation: 'Ignore balances of this token and never send funds to addresses that appear only through it.',
    })
  }

  // ── PG-APPROVAL-001 / 002 ──
  for (const a of approvals) {
    const amt = BigInt(a.allowance)
    if (amt === 0n || !keep(a.spender)) continue
    const known = KNOWN_SPENDERS[a.spender]
    const sym = tokenMeta[a.token]?.symbol || short(a.token)
    const base = [
      { kind: 'onchain_fact', label: 'Token', source: 'ERC-20 contract', value: `${sym} · ${a.token}` },
      { kind: 'onchain_fact', label: 'Spender', source: 'Approval event', value: a.spender + (known ? ` (${known})` : ''), txHash: a.txHash, blockNumber: a.grantedBlock },
      { kind: 'onchain_fact', label: 'Current allowance', source: `allowance() at block ${a.lastBlock ?? 'latest'}`, value: amt >= UNLIMITED_THRESHOLD ? `${amt} (effectively unlimited)` : String(amt), blockNumber: a.lastBlock },
      { kind: 'onchain_fact', label: 'Spender code', source: 'eth_getCode', value: a.spenderIsContract == null ? 'unknown' : a.spenderIsContract ? 'contract' : 'no code (EOA)' },
    ]
    if (a.spenderIsContract === false) {
      findings.push({
        ruleId: 'PG-APPROVAL-002', category: 'Token approval', severity: amt >= UNLIMITED_THRESHOLD ? 'critical' : 'high', confidence: 88,
        title: `${sym} allowance granted to a wallet address (no contract code)`,
        summary: `${short(a.spender)} can spend ${amt >= UNLIMITED_THRESHOLD ? 'an unlimited amount' : 'up to ' + amt + ' base units'} of ${sym} from this wallet and has no contract code.`,
        subjectAddress: s, relatedAddress: a.spender, evidence: base,
        limitations: RULES['PG-APPROVAL-002'].knownFalsePositives,
        recommendation: 'Revoke this allowance unless you deliberately approved this exact address.',
      })
    } else if (amt >= UNLIMITED_THRESHOLD) {
      findings.push({
        ruleId: 'PG-APPROVAL-001', category: 'Token approval', severity: known ? 'low' : 'high', confidence: known ? 60 : 78,
        title: known ? `Unlimited ${sym} allowance to ${known}` : `Unlimited ${sym} allowance to unrecognized spender`,
        summary: known
          ? `${known} holds an unlimited ${sym} allowance. Recognized protocols are not guaranteed safe; unlimited allowances remain exposure if the protocol is compromised.`
          : `An unrecognized ${a.spenderIsContract == null ? 'address' : 'contract'} (${short(a.spender)}) can move your entire ${sym} balance without further signatures.`,
        subjectAddress: s, relatedAddress: a.spender, evidence: base,
        limitations: RULES['PG-APPROVAL-001'].knownFalsePositives + ' "Recognized" means the address is in our label registry — not that it is audited or safe.',
        recommendation: 'Revoke allowances you no longer need, or replace them with exact-amount approvals.',
      })
    }
  }

  for (const f of findings) { f.ruleVersion = METHODOLOGY_VERSION; f.riskScore = SEV_WEIGHT[f.severity] }
  return findings
}

/**
 * Explainable aggregate. riskScore is an ordering heuristic (max severity + 5 per extra finding), NOT a calibrated probability.
 */
export function aggregate(findings, coverage) {
  const transferCoverage = coverage.find((c) => c.source.startsWith('Token transfer history'))
  const historyMissing = !transferCoverage || transferCoverage.status === 'unavailable'
  if (!findings.length) {
    if (historyMissing) return { riskScore: null, riskLabel: 'inconclusive', summary: 'No conclusion: transfer history could not be retrieved, so poisoning rules could not run. This is NOT a clean result.' }
    const partial = coverage.some((c) => c.status !== 'covered')
    return { riskScore: 0, riskLabel: 'low', summary: `No matching findings were detected in the available data${partial ? ' (coverage was partial — see Data coverage)' : ''}. This does not prove the address is safe.` }
  }
  const sorted = [...findings].sort((a, b) => SEV_WEIGHT[b.severity] - SEV_WEIGHT[a.severity])
  const score = Math.min(100, SEV_WEIGHT[sorted[0].severity] + 5 * (findings.length - 1))
  const label = score >= 85 ? 'critical' : score >= 65 ? 'high' : score >= 40 ? 'elevated' : 'low'
  const counts = findings.reduce((m, f) => ((m[f.category] = (m[f.category] || 0) + 1), m), {})
  return {
    riskScore: score, riskLabel: label,
    summary: `${findings.length} finding(s): ${Object.entries(counts).map(([k, v]) => `${v} ${k.toLowerCase()}`).join(', ')}. Findings describe activity observed around this address; the address itself is not proven malicious.`,
  }
}
